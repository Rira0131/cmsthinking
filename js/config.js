  'Pre-IG','IG-V','IG-O','IG-N','IG-K',
  'Pre-A','Pre-R','Pre-C','Pre-H','Pre-E','Pre-S',
  '1레벨','2레벨','3레벨','4레벨','5레벨','6레벨','7레벨',
